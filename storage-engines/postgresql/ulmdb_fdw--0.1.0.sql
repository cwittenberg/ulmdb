CREATE FUNCTION ulmdb_fdw_handler() RETURNS fdw_handler
AS 'MODULE_PATHNAME' LANGUAGE C STRICT;
CREATE FUNCTION ulmdb_fdw_validator(text[], oid) RETURNS void
AS 'MODULE_PATHNAME' LANGUAGE C STRICT;
CREATE FOREIGN DATA WRAPPER ulmdb_fdw
  HANDLER ulmdb_fdw_handler VALIDATOR ulmdb_fdw_validator;
REVOKE ALL ON FOREIGN DATA WRAPPER ulmdb_fdw FROM PUBLIC;
