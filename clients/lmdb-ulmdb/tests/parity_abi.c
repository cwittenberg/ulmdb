/* The same translation unit validates common declarations in all headers. */
#include <lmdb.h>
#include <stddef.h>
#include <stdio.h>

#define TYPE(type) printf(#type " %zu %zu\n", sizeof(type), _Alignof(type))
#define FIELD(type, field) printf(#type "." #field " %zu\n", offsetof(type, field))
#define CONSTANT(name) printf(#name " %ld\n", (long)(name))
int main(void) {
    TYPE(MDB_dbi); TYPE(MDB_val); TYPE(MDB_stat); TYPE(MDB_envinfo); TYPE(MDB_cursor_op);
    FIELD(MDB_val, mv_size); FIELD(MDB_val, mv_data);
    FIELD(MDB_stat, ms_psize); FIELD(MDB_stat, ms_depth); FIELD(MDB_stat, ms_branch_pages);
    FIELD(MDB_stat, ms_leaf_pages); FIELD(MDB_stat, ms_overflow_pages); FIELD(MDB_stat, ms_entries);
    FIELD(MDB_envinfo, me_mapaddr); FIELD(MDB_envinfo, me_mapsize); FIELD(MDB_envinfo, me_last_pgno);
    FIELD(MDB_envinfo, me_last_txnid); FIELD(MDB_envinfo, me_maxreaders); FIELD(MDB_envinfo, me_numreaders);
    CONSTANT(MDB_FIXEDMAP); CONSTANT(MDB_NOSUBDIR); CONSTANT(MDB_NOSYNC); CONSTANT(MDB_RDONLY);
    CONSTANT(MDB_NOMETASYNC); CONSTANT(MDB_WRITEMAP); CONSTANT(MDB_MAPASYNC); CONSTANT(MDB_NOTLS);
    CONSTANT(MDB_NOLOCK); CONSTANT(MDB_NORDAHEAD); CONSTANT(MDB_NOMEMINIT);
    CONSTANT(MDB_REVERSEKEY); CONSTANT(MDB_DUPSORT); CONSTANT(MDB_INTEGERKEY);
    CONSTANT(MDB_DUPFIXED); CONSTANT(MDB_INTEGERDUP); CONSTANT(MDB_REVERSEDUP); CONSTANT(MDB_CREATE);
    CONSTANT(MDB_NOOVERWRITE); CONSTANT(MDB_NODUPDATA); CONSTANT(MDB_CURRENT); CONSTANT(MDB_RESERVE);
    CONSTANT(MDB_APPEND); CONSTANT(MDB_APPENDDUP); CONSTANT(MDB_MULTIPLE); CONSTANT(MDB_CP_COMPACT);
    CONSTANT(MDB_SUCCESS); CONSTANT(MDB_KEYEXIST); CONSTANT(MDB_NOTFOUND); CONSTANT(MDB_PAGE_NOTFOUND);
    CONSTANT(MDB_CORRUPTED); CONSTANT(MDB_PANIC); CONSTANT(MDB_VERSION_MISMATCH); CONSTANT(MDB_INVALID);
    CONSTANT(MDB_MAP_FULL); CONSTANT(MDB_DBS_FULL); CONSTANT(MDB_READERS_FULL); CONSTANT(MDB_TLS_FULL);
    CONSTANT(MDB_TXN_FULL); CONSTANT(MDB_CURSOR_FULL); CONSTANT(MDB_PAGE_FULL); CONSTANT(MDB_MAP_RESIZED);
    CONSTANT(MDB_INCOMPATIBLE); CONSTANT(MDB_BAD_RSLOT); CONSTANT(MDB_BAD_TXN); CONSTANT(MDB_BAD_VALSIZE); CONSTANT(MDB_BAD_DBI);
    CONSTANT(MDB_FIRST); CONSTANT(MDB_FIRST_DUP); CONSTANT(MDB_GET_BOTH); CONSTANT(MDB_GET_BOTH_RANGE);
    CONSTANT(MDB_GET_CURRENT); CONSTANT(MDB_GET_MULTIPLE); CONSTANT(MDB_LAST); CONSTANT(MDB_LAST_DUP);
    CONSTANT(MDB_NEXT); CONSTANT(MDB_NEXT_DUP); CONSTANT(MDB_NEXT_MULTIPLE); CONSTANT(MDB_NEXT_NODUP);
    CONSTANT(MDB_PREV); CONSTANT(MDB_PREV_DUP); CONSTANT(MDB_PREV_NODUP); CONSTANT(MDB_SET);
    CONSTANT(MDB_SET_KEY); CONSTANT(MDB_SET_RANGE); CONSTANT(MDB_PREV_MULTIPLE);
    return 0;
}
